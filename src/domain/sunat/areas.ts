    DECLARACION_JURADA_MENSUAL: 'INTENDENCIA_RECAUDACION_CONTROL_MASIVO',
    DECLARACION_JURADA_ANUAL: 'INTENDENCIA_RECAUDACION_CONTROL_MASIVO',
    RESOLUCION_FRACCIONAMIENTO: 'INTENDENCIA_RECAUDACION_CONTROL_MASIVO',
